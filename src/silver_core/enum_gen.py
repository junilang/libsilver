n = 64

out = open("src/silver_core/enum_gen.h", "w")

print("// this file was automatically generated by enum_gen.py", file=out)

for i in range(1, n):
	print(
		f"#define ENUM_{i}(pfx, v, ...) " +
	 	f"ENUM_X##__VA_OPT__(OPT)(pfx, v) " +
		f"__VA_OPT__(,ENUM_{i+1}(pfx, __VA_ARGS__))",
		file=out, end="\n"
	)

	print(
		f"#define ENUM_STR_{i}(pfx, v, ...) " +
	 	f"ENUM_STR_X(pfx, v)__VA_OPT__(,ENUM_STR_{i+1}(pfx, __VA_ARGS__))",
		file=out, end="\n"
	)

print(
	f"#define ENUM_{n}(...) ENUM_ERROR_TOO_MANY_VALUES",
	file=out, end="\n"
)

print(
	f"#define ENUM_STR_{n}(...) ENUM_ERROR_TOO_MANY_VALUES",
	file=out, end="\n"
)
