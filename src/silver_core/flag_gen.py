n = 64

out = open("src/silver_core/flag_gen.h", "w")

print("// this file was automatically generated by flag_gen.py", file=out)

for i in range(1, n):
	print(
		f"#define FLAGS_{i}(pfx, flag, ...) " +
	 	f"FLAG(pfx##flag)__VA_OPT__(|FLAGS_{i+1}(pfx, __VA_ARGS__))",
		file=out, end="\n"
	)

	print(
		f"#define FLAGS_DEF_{i}(pfx, flag, ...) " +
	 	f"FLAG_DEF(pfx##flag)__VA_OPT__(,FLAGS_DEF_{i+1}(pfx, __VA_ARGS__))",
		file=out, end="\n"
	)

print(
	f"#define FLAGS_{n}(...) FLAG_ERROR_TOO_MANY_FLAGS",
	file=out, end="\n"
)

print(
	f"#define FLAGS_DEF_{n}(...) FLAG_ERROR_TOO_MANY_FLAGS",
	file=out, end="\n"
)
